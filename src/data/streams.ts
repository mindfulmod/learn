export function getStream(id: string | undefined): Stream | undefined {
  return id ? STREAMS.find((s) => s.id === id) : undefined
}

export function streamsFor(boardId: BoardId, stageId: StageId): Stream[] {
  return STREAMS.filter((s) => s.boardId === boardId && s.stageId === stageId)
}

/** All subject ids a stream can include (compulsory plus electives). */
export function streamSubjects(stream: Stream): string[] {
  return [...stream.compulsory, ...(stream.electives?.from ?? [])]
}
